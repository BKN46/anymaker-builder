// Extract the six published cylinder endpoints; no game install is required.
import { readFile, writeFile } from 'node:fs/promises';
const profiles = {};
for (const suffix of ['', '_2_2', '_3_3']) for (const role of ['base', 'rod']) {
  const id = 'hydraulic_cylinder_connector' + (role === 'base' ? '_base' : '') + suffix;
  const definition = JSON.parse(await readFile('public/data/definitions/' + id + '.json', 'utf8'));
  profiles[id] = { logic_nodes: definition.logic_nodes, surfaces: definition.surfaces };
}
await writeFile('src/editor/hydraulic-profiles.js', '// Generated by scripts/extract-hydraulic-profiles.mjs from published definitions.\nexport const HYDRAULIC_PROFILES = ' + JSON.stringify(profiles, null, 2) + ';\n');
