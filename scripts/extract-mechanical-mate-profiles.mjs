// Small synchronous mate descriptors, derived from the published definitions.
// No ROM input and no Mesh regeneration. Run from the repository root.
import { readFile, readdir, writeFile } from 'node:fs/promises';

const profiles = {};
const definitions = new Map(); const types = new Set();
for (const name of (await readdir('public/data/definitions')).filter(name => name.endsWith('.json')).sort()) {
  const definition = JSON.parse(await readFile(`public/data/definitions/${name}`, 'utf8'));
  definitions.set(name.slice(0, -5), definition);
  for (const [key, value] of Object.entries(definition)) if (key.endsWith('_definition_id_other')) {
    types.add(name.slice(0, -5)); types.add(value);
  }
}
for (const type of [...types].sort()) {
  const definition = definitions.get(type);
  if (!definition) throw new Error('Missing mechanical mate definition: ' + type);
  profiles[type] = Object.fromEntries(Object.entries(definition).filter(([key]) => ['id', 'surfaces', 'center_stretch', 'ext_max', 'interval', 'mode_x', 'mode_y', 'mode_z'].includes(key) || /^(constraint_|hinge_|mounting_|rail_|latch_|tow_hitch_)/.test(key)));
}
await writeFile('src/editor/mechanical-mate-profiles.js', '// Generated by scripts/extract-mechanical-mate-profiles.mjs from public/data/definitions.\nexport const MECHANICAL_MATE_PROFILES = ' + JSON.stringify(profiles, null, 2) + ';\n');
